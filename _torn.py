# -*- coding: utf-8 -*-
"""Generate realistic torn-paper silhouettes.

A real tear is not a sine wave: it is a random walk along the edge made of
short straight fibres, with occasional deep bites and splinters. We sample
the edge every ~0.7% with a random walk (not independent jitter), which
gives long runs, sharp reversals and the asymmetric look of torn stock.

Outputs:
  _src/07_torn.css   → CSS classes for the site cards
  _src/torn.json     → {wide:[{clip,core}], card:[{clip,core}]} for katalog
"""
import json, os, random, sys

ROOT = os.path.dirname(os.path.abspath(__file__))


def edge(rnd, n, depth, bite=0.22, hold=0.18):
    """Ragged tear line: a persistent random walk with torn-out bites.

    The walk is normalised first (so it never saturates into a wave), then
    scaled to `depth` percent, so the edge stays ragged everywhere instead
    of hugging a clamp boundary.
    """
    import math
    vals, v = [], 0.0
    for i in range(n + 1):
        if rnd.random() < hold:          # a short fibre holds the line straight
            vals.append(v)
            continue
        v = v * 0.74 + rnd.gauss(0, 1.0)
        vals.append(v)
    # bites: localised inward dents where a strip came away
    for _ in range(max(2, int(n * bite))):
        c = rnd.randint(0, n)
        w = rnd.randint(1, 4)
        d = rnd.uniform(0.7, 2.1)
        for k in range(max(0, c - w), min(n, c + w) + 1):
            vals[k] += d * math.cos((k - c) / max(1, w) * math.pi / 2)
    m = sum(vals) / len(vals)
    vals = [x - m for x in vals]
    mx = max(abs(x) for x in vals) or 1.0
    vals = [x / mx for x in vals]
    out = []
    for i, x in enumerate(vals):
        t = i / n
        taper = min(1.0, t / 0.015, (1 - t) / 0.015)   # keep the corners
        out.append(depth + x * depth * taper)          # 0 … 2·depth
    return out


def torn_paths(seed, n=110, depth=1.9, split=0.42):
    """returns (front_polygon, core_polygon) in 0..100 % coordinates"""
    rnd = random.Random(seed)

    def shell(rnd2, d):
        bx = edge(rnd2, n, d)                    # top / bottom (y offsets)
        by = edge(rnd2, n, d)                    # left / right (x offsets)
        by2 = edge(rnd2, n, d)
        bx2 = edge(rnd2, n, d)
        pts = []
        # top, left→right
        for i in range(n + 1):
            pts.append((max(0, min(100, i * 100 / n + rnd2.gauss(0, .18))),
                        max(0.05, min(6.5, 0.4 + bx[i]))))
        # right, top→bottom
        for i in range(n + 1):
            pts.append((min(99.95, max(93.5, 99.6 + by[i])),
                        max(0, min(100, i * 100 / n + rnd2.gauss(0, .18)))))
        # bottom, right→left
        for i in range(n + 1):
            pts.append((max(0, min(100, 100 - i * 100 / n + rnd2.gauss(0, .18))),
                        min(99.95, max(93.5, 99.6 + bx2[i]))))
        # left, bottom→top
        for i in range(n + 1):
            pts.append((max(0.05, min(6.5, 0.4 + by2[i])),
                        max(0, min(100, 100 - i * 100 / n + rnd2.gauss(0, .18)))))
        return pts

    front = shell(random.Random(seed), depth)
    # the fibrous core is the same tear pushed outward by a fixed margin,
    # so a thin pale rim always shows under the dark sheet
    core = []
    for (x, y) in front:
        dx, dy = x - 50.0, y - 50.0
        L = max(1e-6, (dx * dx + dy * dy) ** 0.5)
        m = split + random.Random(seed).uniform(0, 0.06)
        core.append((max(0.0, min(100.0, x + dx / L * m)),
                     max(0.0, min(100.0, y + dy / L * m))))
    def poly(p):
        return "polygon(" + ",".join(f"{x:.2f}% {y:.2f}%" for x, y in p) + ")"
    return poly(front), poly(core)


def build():
    wide, card = [], []
    for k in range(10):
        f, c = torn_paths(100 + k * 13, n=150, depth=1.05, split=0.30)
        wide.append({"clip": f, "core": c})
    for k in range(10):
        f, c = torn_paths(400 + k * 29, n=110, depth=1.35, split=0.34)
        card.append({"clip": f, "core": c})

    json.dump({"wide": wide, "card": card},
              open(os.path.join(ROOT, "_src", "torn.json"), "w"), indent=0)

    css = ["/* torn edges — generated by _torn.py, do not edit by hand */"]
    for i, v in enumerate(card):
        css.append(f".card[data-torn=\"{i}\"],.geo[data-torn=\"{i}\"],.tl-item[data-torn=\"{i}\"]"
                   f"{{--clip:{v['clip']};--core:{v['core']}}}")
    open(os.path.join(ROOT, "_src", "07_torn.css"), "w").write("\n".join(css) + "\n")
    print("variants:", len(wide), "wide ·", len(card), "card")
    print("css bytes:", len("\n".join(css)))


if __name__ == "__main__":
    build()
