# -*- coding: utf-8 -*-
import base64, io, json, os
from PIL import Image
ROOT = os.path.dirname(os.path.abspath(__file__))
MAN = json.load(open(os.path.join(ROOT, "assets", "img", "manifest.json"), encoding="utf-8"))
out, meta = {}, {}
tot = 0
for k in MAN:
    im = Image.open(os.path.join(ROOT, "assets", "img", k + ".jpg")).convert("RGB")
    im = im.resize((520, 347), Image.LANCZOS)
    buf = io.BytesIO(); im.save(buf, "JPEG", quality=57, optimize=True, progressive=True)
    b = buf.getvalue(); tot += len(b)
    out[k] = "data:image/jpeg;base64," + base64.b64encode(b).decode()
    meta[k] = {"kind": MAN[k]["kind"], "credit": MAN[k]["credit"]}
js = ("/* PLATES — drawer thumbnails, generated by _gen_plates.py */\n"
      "const PLATES = " + json.dumps(out) + ";\n"
      "const PLATE_META = " + json.dumps(meta, ensure_ascii=False) + ";\n")
open(os.path.join(ROOT, "_src", "04c_plates.js"), "w", encoding="utf-8").write(js)
print("plates:", len(out), "raw", tot // 1024, "KB -> b64", int(tot * 1.37) // 1024, "KB")
