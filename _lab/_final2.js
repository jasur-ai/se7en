const { chromium, devices } = require('playwright');
(async () => {
  const b = await chromium.launch();
  const errs = []; const URL_ = 'https://se7en-omega.vercel.app/';
  const ctx = await b.newContext({ viewport: { width: 1440, height: 1000 } });
  const p = await ctx.newPage();
  p.on('pageerror', e => errs.push('D ' + e.message.slice(0,80)));
  await p.goto(URL_, { waitUntil: 'load' });
  await p.waitForTimeout(700);
  await p.screenshot({ path: '/tmp/lv_d1.png' });
  await p.evaluate(() => document.querySelector('#zanjir').scrollIntoView());
  await p.waitForTimeout(600);
  await p.screenshot({ path: '/tmp/lv_d2.png' });
  const info = await p.evaluate(() => ({ brand: document.querySelector('.brand b').textContent, h1: document.querySelector('h1').textContent, deck: document.querySelectorAll('#pzDeck .card').length, src: document.querySelectorAll('#src li').length }));
  await ctx.close();
  const c2 = await b.newContext({ ...devices['iPhone 13'], deviceScaleFactor: 2 });
  const m = await c2.newPage();
  m.on('pageerror', e => errs.push('M ' + e.message.slice(0,80)));
  await m.goto(URL_, { waitUntil: 'load' });
  await m.waitForTimeout(800);
  await m.screenshot({ path: '/tmp/lv_m1.png' });
  await m.evaluate(() => document.querySelector('#zanjir').scrollIntoView());
  await m.waitForTimeout(500);
  const k = await m.evaluate(() => document.querySelector('#pzDeck .card').dataset.card);
  await m.tap(`#pzDeck [data-card="${k}"]`); await m.waitForTimeout(400);
  await m.screenshot({ path: '/tmp/lv_m2.png' });
  await m.tap('#pzPut [data-put="0"]'); await m.waitForTimeout(300);
  await m.tap('#pzCheck'); await m.waitForTimeout(600);
  const st = await m.evaluate(() => ({ status: document.querySelector('#pzStatus').textContent, count: document.querySelector('#pzCount').textContent, ox: document.documentElement.scrollWidth - innerWidth }));
  console.log(JSON.stringify({ info, st, errs }, null, 1));
  await b.close();
})();
